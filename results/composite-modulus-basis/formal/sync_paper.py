"""Generate the paper/Lean concordance from one reviewed declaration map.

--check verifies that the committed audit, tables and Markdown agree with the
map, and that both manuscript languages contain the mapped labels.
"""

import argparse
from collections import defaultdict
import json
from pathlib import Path
import re


ROOT = Path(__file__).resolve().parent.parent


def load_map():
    data = json.loads((ROOT / "paper/theorem-map.json").read_text())
    ids = [claim["id"] for claim in data["claims"]]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate paper label")
    return data


def declarations(data):
    return list(dict.fromkeys(name for claim in data["claims"] for name in claim["declarations"]))


def source_location(name):
    prefix = "CompositeModulusBasis."
    assert name.startswith(prefix), name
    module, declaration = name[len(prefix):].split(".", 1)
    path = ROOT / "formal/LeanVerification" / f"{module}.lean"
    text = path.read_text()
    pattern = r"^[ \t]*(?:(?:noncomputable|private|protected)[ \t]+)*(?:theorem|def|structure|abbrev)\s+" + re.escape(declaration) + r"\b"
    match = re.search(pattern, text, re.MULTILINE)
    if match is None and name.endswith("CorrectTable.card_at"):
        match = re.search(r"^  card_at :", text, re.MULTILINE)
    if match is None:
        raise ValueError(f"declaration source not found: {name}")
    line = text[:match.start()].count("\n") + 1
    return path.relative_to(ROOT).as_posix(), line


def generate(data):
    outputs = {}
    names = declarations(data)
    outputs[ROOT / "formal/Audit.lean"] = (
        "import LeanVerification\n\n"
        "-- Generated by sync_paper.py from paper/theorem-map.json.\n"
        "-- Core declarations only; finite native_decide regression is not imported.\n"
        + "\n".join(f"#print axioms {name}" for name in names) + "\n"
    )
    for lang in ("zh", "en"):
        zh = lang == "zh"
        kinds = {"definition": "定义" if zh else "Definition", "lemma": "引理" if zh else "Lemma", "theorem": "定理" if zh else "Theorem", "corollary": "推论" if zh else "Corollary", "proposition": "命题" if zh else "Proposition"}
        title = "论文—Lean 4 证明对照" if zh else "Paper–Lean 4 proof concordance"
        intro = (
            "本文件由 `formal/sync_paper.py` 从 `paper/theorem-map.json` 生成，声明源链接和论文编号自动同步。\n\n"
            "“机器证明”表示对应数学声明已被 Lean 检查；“仅事件计数”表示实现成本契约仍由文字分析给出。\n"
            if zh else
            "Generated by `formal/sync_paper.py` from `paper/theorem-map.json`; source links and paper numbering are synchronized.\n\n"
            "“Kernel checked” covers the mathematical declaration. “Event counts only” leaves implementation cost contracts to the written analysis.\n"
        )
        md = [f"# {title}\n", intro,
              "| 论文 | 结论 | 范围 | Lean 声明 |\n|---|---|---|---|" if zh else "| Paper | Claim | Scope | Lean declaration |\n|---|---|---|---|"]
        latex = [r"\begin{longtable}{@{}>{\raggedright\arraybackslash}p{0.10\linewidth}>{\raggedright\arraybackslash}p{0.25\linewidth}>{\raggedright\arraybackslash}p{0.59\linewidth}@{}}",
                 (r"\caption{论文与 Lean 声明对照。}\label{tab:concordance}\\" if zh else
                  r"\caption{Paper--Lean concordance.}\label{tab:concordance}\\"),
                 r"\toprule", r"编号 & 结论 & Lean 声明 \\" if zh else r"Item & Claim & Lean declaration \\", r"\midrule\endfirsthead",
                 r"\toprule", r"编号 & 结论 & Lean 声明 \\" if zh else r"Item & Claim & Lean declaration \\", r"\midrule\endhead", r"\bottomrule\endfoot"]
        counters = defaultdict(int)
        for claim in data["claims"]:
            counters[claim["kind"]] += 1
            number = counters[claim["kind"]]
            item = f'{kinds[claim["kind"]]} {number}'
            scope = ("机器证明" if zh else "Kernel checked") if claim["status"] == "formal" else ("仅事件计数" if zh else "Event counts only")
            links, lean_names = [], []
            for name in claim["declarations"]:
                source, line = source_location(name)
                short = name.removeprefix("CompositeModulusBasis.")
                links.append(f"[`{short}`](../../{source}#L{line})")
                lean_names.append(r"\Lean{" + short + "}")
            md.append(f'| {item} (`{claim["id"]}`) | {claim[f"title_{lang}"]} | {scope} | ' + "<br>".join(links) + " |")
            short_kind = kinds[claim["kind"]] if zh else {"definition": "Def.", "lemma": "Lem.", "theorem": "Thm.", "corollary": "Cor.", "proposition": "Prop."}[claim["kind"]]
            label = short_kind + r"~\ref{" + claim["id"] + "}"
            claim_title = claim[f"title_{lang}"]
            if claim["status"] != "formal":
                claim_title += "（仅事件计数）" if zh else " (event counts only)"
            latex.append(label + " & " + claim_title + " & " + r"\newline ".join(lean_names) + r" \\")
            latex.append(r"\addlinespace[0.55em]")
        latex.append(r"\end{longtable}")
        outputs[ROOT / f"docs/{lang}/proof-map.md"] = "\n".join(md) + "\n"
        outputs[ROOT / f"paper/concordance-{lang}.tex"] = "\n".join(latex) + "\n"
    return outputs


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = load_map()
    outputs = generate(data)
    if args.check:
        for path, expected in outputs.items():
            if not path.exists() or path.read_text() != expected:
                raise SystemExit(f"Outdated generated file: {path.relative_to(ROOT)}; run make map")
        for lang in ("zh", "en"):
            text = (ROOT / f"paper/main-{lang}.tex").read_text()
            labels = re.findall(r"\\label\{([^}]+)\}", text)
            for claim in data["claims"]:
                if labels.count(claim["id"]) != 1:
                    raise SystemExit(f"Missing or duplicate {lang} label: {claim['id']}")
        print(f"PASS paper concordance: {len(data['claims'])} numbered claims, {len(declarations(data))} Lean declarations")
    else:
        for path, content in outputs.items():
            path.write_text(content)
        print(f"Generated {len(outputs)} concordance/audit files")


if __name__ == "__main__":
    main()
